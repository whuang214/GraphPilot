def _runtime_frontend_origin():
    """The launcher's frontend origin, if a launcher is running.

    `run.py` writes this beside the repository while it holds its ports, because the MCP
    server is started by the IDE and shares no environment with it. Anything unreadable
    or unrecognised means "no launcher": a stale or hand-edited file must not be able to
    send a host to an arbitrary URL, and it must never stop Django starting.
    """
    try:
        payload = json.loads(
            (BASE_DIR.parent / ports.RUNTIME_FILENAME).read_text(encoding='utf-8')
        )
        origin = str(payload['frontendOrigin']).strip().rstrip('/')
    except (OSError, ValueError, KeyError, TypeError):
        return None
    return origin if origin.startswith(('http://localhost:', 'http://127.0.0.1:')) else None


