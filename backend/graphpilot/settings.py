# GraphPilot-specific settings

# There was a GRAPHPILOT_DEFAULT_WORKSPACE_DIR here, read by nothing. Every MCP tool
# takes `workspaceDir` per call, which is the design: a host says which repository it
# is diagramming, and a default would have nothing to default to.
GRAPHPILOT_STORAGE_DIR = os.environ.get('GRAPHPILOT_STORAGE_DIR', '.graphpilot')
# Base URL of the React frontend, used by the MCP tools to build the returned editUrl
# (`<base>/editor?diagramPath=<path>`).
#
# Two things can be running: the hand-started dev server, and the double-clicked
# launcher on its own ports. Setting this to a *third* place pins the answer; leaving it
# at the dev origin (or empty) lets `services.shared.editor_origin` resolve which of the
# two is actually up.
#
# `.env` describes the **dev** setup — that is what its CORS line and the frontend's
# `VITE_API_BASE_URL` are for — so a value that simply *is* the dev origin is the
# template speaking, not a decision. Treating it as a pin is what broke this first: every
# install shipped `=http://localhost:5173`, so the resolver never ran and anyone using
# only the launcher got a well-formed link to a port nothing was serving.
_frontend_base_url = os.environ.get('GRAPHPILOT_FRONTEND_BASE_URL', '').strip().rstrip('/')
GRAPHPILOT_FRONTEND_BASE_URL_EXPLICIT = (
    _frontend_base_url if _frontend_base_url != ports.dev_frontend_origin() else ''
)
GRAPHPILOT_FRONTEND_BASE_URL = _frontend_base_url or ports.dev_frontend_origin()

# Written by `run.py` while the launcher is running, so the IDE-spawned MCP server — a
# process the launcher never started — can discover which port the app actually got.
GRAPHPILOT_RUNTIME_FRONTEND_ORIGIN = _runtime_frontend_origin()
# The diagram file extension (".gp.json") + empty-name fallback ("diagram") are
# owned by WorkspaceStorageService's built-in default; no setting/env var is needed
